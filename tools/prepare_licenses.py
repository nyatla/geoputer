"""Generate flash-resident, 29-column ASCII license lines for 8-dot text."""
import json
from pathlib import Path
import re
import textwrap
import unicodedata

root = Path(__file__).resolve().parents[1]
source = root / "third_party/licenses"
manifest = json.loads((source / "manifest.json").read_text())
lines = ["GEOPUTER OSS LICENSES", "", "UP/DOWN SCROLL; <> SOFTWARE", "ESC/DEL: SETTINGS", ""]
sections = []
for item in manifest:
    document = (source / item.get("display_file", item["file"])).read_text()
    document = re.sub(r"\[([^\]]+)\]\(([^)]+)\)", r"\1 (\2)", document)
    document = document.translate(str.maketrans({"\u201c": '"', "\u201d": '"', "\u2018": "'", "\u2019": "'", "\u2013": "-", "\u2014": "--", "\ufeff": ""}))
    document = unicodedata.normalize("NFKC", document)
    assert document.isascii() and item["name"].isascii(), item["name"]
    lines.extend(["-" * 29])
    sections.append(len(lines))  # Software title, immediately after its divider.
    for paragraph in (item["name"] + "\n\n" + document).splitlines():
        paragraph = paragraph.expandtabs(4).strip().lstrip("#").strip()
        if paragraph.startswith("```"):
            continue
        lines.extend(textwrap.wrap(paragraph, width=29, break_long_words=True, break_on_hyphens=False) or [""])
    lines.extend(["", ""])
assert all(offset + 9 <= len(lines) for offset in sections), "Every section must fit at the viewport top"
encoded = ",\n".join("    " + json.dumps(line, ensure_ascii=False) for line in lines)
output = root / "application/task/ui/LicenseText.cpp"
output.write_text(
    '// Generated by tools/prepare_licenses.py. Notices live in third_party/licenses.\n'
    '#include "LicenseText.h"\n\nnamespace geoputer {\nnamespace {\n'
    'const char* const Lines[] = {\n' + encoded + '\n};\n'
    'const uint32_t Sections[] = {' + ', '.join(map(str, sections)) + '};\n}\n'
    'size_t licenseLineCount() { return sizeof(Lines) / sizeof(Lines[0]); }\n'
    'const char* licenseLine(size_t index) { return index < licenseLineCount() ? Lines[index] : ""; }\n'
    'size_t licenseSectionCount() { return sizeof(Sections) / sizeof(Sections[0]); }\n'
    'size_t licenseSectionStart(size_t index) { return index < licenseSectionCount() ? Sections[index] : licenseLineCount(); }\n'
    '}  // namespace geoputer\n'
)
print(f"Generated {len(lines)} lines from {len(manifest)} license entries")
