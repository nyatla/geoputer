"""Generate a flash-resident CP932 -> Unicode table using Python's standard codec."""
from pathlib import Path

root = Path(__file__).resolve().parents[1]
values = []
for lead in [*range(0x81, 0xA0), *range(0xE0, 0xFD)]:
    for trail in [*range(0x40, 0x7F), *range(0x80, 0xFD)]:
        try:
            value = ord(bytes([lead, trail]).decode("cp932"))
        except UnicodeDecodeError:
            value = 0
        assert value <= 0xFFFF
        values.append(value)
lines = ["    " + ", ".join(f"0x{x:04X}" for x in values[i:i+12]) + ","
         for i in range(0, len(values), 12)]
target = root / "application/task/storage/galuchat/Cp932Table.inc"
target.write_text("// Generated by tools/prepare_cp932.py; zero means undefined.\n" +
                  "\n".join(lines) + "\n")
print(f"Generated {len(values)} CP932 entries ({len(values)*2} bytes in flash)")
