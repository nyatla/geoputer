"""Generate native 16x16 Shinonome glyphs from the pinned, unmodified sources."""
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "third_party/shinonome"


def read_glyphs(path):
    lines = path.read_text().splitlines()
    glyphs = {}
    encoding = None
    width = None
    for i, line in enumerate(lines):
        if line.startswith("ENCODING "):
            encoding = int(line.split()[1])
        elif line.startswith("BBX "):
            width, height, x, y = map(int, line.split()[1:])
            assert (width, height, x, y) in [(8, 16, 0, -2), (16, 16, 0, -2)]
        elif line == "BITMAP":
            pixels = lines[i + 1:i + 17]
            assert len(pixels) == 16 and all(len(row) == width and set(row) <= {".", "@"} for row in pixels)
            # Native eight-dot-wide forms are centered in the 16-dot cell.
            glyphs[encoding] = tuple(int(row.replace(".", "0").replace("@", "1"), 2)
                                     << (4 if width == 8 else 0) for row in pixels)
    return glyphs


def build():
    metadata = json.loads((SOURCE / "source.json").read_text())
    for entry in metadata["files"]:
        assert hashlib.sha256((SOURCE / entry["path"]).read_bytes()).hexdigest() == entry["sha256"], entry["path"]
    result = {}
    for code, rows in read_glyphs(SOURCE / "16/kanjic/font_src.bit").items():
        character = bytes([code >> 8 | 0x80, code & 0xFF | 0x80]).decode("euc_jp")
        result[ord(character)] = rows
    # Unicode compatibility forms share the original punctuation glyphs.
    for original, alternate in ((0x301C, 0xFF5E), (0x2016, 0x2225), (0x2212, 0xFF0D),
                                (0x00A2, 0xFFE0), (0x00A3, 0xFFE1), (0x00AC, 0xFFE2)):
        result[alternate] = result[original]
    latin = read_glyphs(SOURCE / "16/latin1/font_src.bit")
    for code, rows in latin.items():
        if code >= 0x20:
            result.setdefault(code, rows)
    for code, rows in read_glyphs(SOURCE / "16/hankaku/font_src_diff.bit").items():
        if 0xA1 <= code <= 0xDF:
            result[0xFF61 + code - 0xA1] = rows
    # Use Shinonome's native full-width Latin forms in the fixed 16x16 grid.
    # Quotes/symbols absent from JIS X 0208 use its native 8x16 Latin glyphs.
    for code in range(0x20, 0x7F):
        full_width = 0x3000 if code == 0x20 else code + 0xFEE0
        result[code] = result.get(full_width, latin[code])
    assert 0x25A1 in result and all(cp <= 0xFFFF for cp in result)
    return result


if __name__ == "__main__":
    glyphs = build()
    output = ROOT / "application/task/ui/ShinonomeData.inc"
    output.write_text(
        "// Generated by tools/prepare_shinonome.py; see third_party/shinonome.\n" +
        "\n".join("    {0x%04X, {%s}}," % (cp, ", ".join("0x%04X" % row for row in rows))
                  for cp, rows in sorted(glyphs.items())) + "\n")
    print(f"Generated {len(glyphs)} Shinonome glyphs ({len(glyphs) * 34} flash bytes)")
